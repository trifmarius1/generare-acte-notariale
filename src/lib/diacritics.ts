function applyCase(source: string, fixed: string): string {
  if (source === source.toLocaleUpperCase('ro-RO') && source.length <= 3) return source;
  if (source === source.toLocaleUpperCase('ro-RO')) return fixed.toLocaleUpperCase('ro-RO');
  if (source[0] === source[0]?.toLocaleUpperCase('ro-RO')) {
    return fixed[0].toLocaleUpperCase('ro-RO') + fixed.slice(1);
  }
  return fixed;
}

export function restoreDiacritics(text: string): string {
  return text.replace(/\p{L}+/gu, (word) => {
    const fixed = WORDS[word.toLocaleLowerCase('ro-RO')];
    return fixed ? applyCase(word, fixed) : word;
  });
}
